/** The flow a task is started (or resumed) in; checks that it is tracked and active. */
function selectFlow(paths: ProjectPaths, cfg: TrackerConfig, issue: JiraIssue, record: TaskRecord | undefined, requested: string | undefined): FlowModel {
  const key = issue.key;
  let name: string;
  let why: string;
  if (record) {
    if (requested !== undefined && requested !== record.flow) throw flowMismatchError(key, record.flow, requested);
    name = record.flow;
    why = `${key} is a task of flow "${name}"`;
  } else if (requested !== undefined) {
    name = requested;
    why = `You asked to start ${key} in flow "${name}"`;
  } else {
    const type = issue.fields.issuetype.name;
    const byType = Object.entries(cfg.flowSelect.byIssueType).find(([t]) => nameMatches(t, issue.fields.issuetype))?.[1];
    if (byType !== undefined) {
      name = byType;
      why = `${key} is a ${type}, which uses flow "${name}" (flowSelect.byIssueType in ${TRACKER_FILE_LABEL})`;
    } else if (cfg.flowSelect.default !== undefined) {
      name = cfg.flowSelect.default;
      why = `${key} uses flow "${name}" (flowSelect.default in ${TRACKER_FILE_LABEL})`;
    } else {
      name = getActiveFlowName(paths) ?? loadActiveFlow(paths).name;
      why = `${key} uses the active flow "${name}"`;
    }
  }
  const model = loadFlow(paths, name);
  if (!trackedFlow(cfg, name)) {
    throw new DflError(`${why}, which is not tracked in Jira (${TRACKER_FILE_LABEL} has no "flows.${name}").`, {
      hint: `Track it with \`dfl tracker map --flow ${name}\`${record ? '' : ', or pass another flow'}.`,
      code: 'TRACKER_FLOW_NOT_MAPPED',
    });
  }
  const active = getActiveFlowName(paths);
  if (active !== name) {
    throw new DflError(`${why}, but ${active !== undefined ? `the active flow is "${active}"` : 'no flow is active'}.`, {
      hint:
        `Switch with \`dfl flow use ${name}\` and run the command again (restart your agent if it does not pick up the new skills)` +
        `${record ? '' : ', or pass the flow to start it in'}.`,
      code: 'TASK_FLOW_NOT_ACTIVE',
    });
  }
  return model;
}

/** What a start_task call works with besides the flow and the ticket. */
interface StartContext {
  paths: ProjectPaths;
  cfg: TrackerConfig;
  /** The ticket as the caller named it (normalized key). */
  ref: string;
  mode: BranchMode;
  slug: string | undefined;
  credential: TrackerCredential;
  warnings: string[];
  opts: TaskWriteOptions;
}

/**
 * A started task: where its branch is, without writes ({@link resumeView}). When the record has no
 * branch, one is chosen (and created) as for a new task and recorded under the lock ({@link bindBranch}).
 */
async function resume(ctx: StartContext, model: FlowModel, issue: JiraIssue, record: TaskRecord): Promise<StartTaskResult> {
  const { paths, cfg, warnings } = ctx;
  const key = issue.key;
  assertNotDone(model, key, record);
  if (record.params['branch']) return resumeView(paths, cfg, model, issue, record, warnings);

  // No branch recorded (a record a goto repaired, or the param was deleted): never report the
  // checked-out branch as the task's unless its name names the task.
  assertConfiguredKey(cfg, ctx.ref, key);
  const settings = resolveBranchSettings(paths, cfg, model.def);
  const plan = planBranch(paths, cfg, settings, { key, summary: issue.fields.summary, head: currentBranch(paths.root), mode: ctx.mode, slug: ctx.slug });
  if (plan.action === 'create') await createTaskBranch(paths.root, plan, settings, warnings);
  return ctx.opts.withLock(async () => {
    const client = clientFor(cfg, ctx.credential);
    const fresh = await client.getIssue(key, { properties: [cfg.jira.property], fields: mappedFieldIds(cfg) });
    const again = readRecord(fresh.properties[cfg.jira.property], fresh);
    if (again.kind === 'invalid') throw again.error;
    if (again.kind !== 'ok') throw notStartedError(key, ctx.opts.commandPrefix);
    if (again.record.flow !== model.name) throw flowMismatchError(key, again.record.flow, model.name);
    if (again.record.params['branch']) {
      warnings.push(`Another dfl process recorded the branch of ${key} meanwhile; dfl kept it.`);
      return resumeView(paths, cfg, model, fresh, again.record, warnings);
    }
    return bindBranch(ctx, client, model, fresh, again.record, plan);
  });
}

/**
 * Records the branch of `plan` in the params of a started task that has none (under the lock; the
 * step and the ticket's status stay), then writes the mapped fields. `issue` was read with
 * {@link mappedFieldIds}.
 */
async function bindBranch(
  ctx: StartContext,
  client: JiraClient,
  model: FlowModel,
  issue: JiraIssue,
  record: TaskRecord,
  plan: BranchPlan,
): Promise<StartTaskResult> {
  const { cfg, warnings } = ctx;
  const key = issue.key;
  assertNotDone(model, key, record);
  const slug = record.params['slug'] ? {} : { slug: plan.slug !== '' ? plan.slug : key.toLowerCase() };
  const { params } = mergeParams(record.params, { branch: plan.name, ...slug });
  const next = buildRecord({ previous: record, issueId: issue.id, key, flow: record.flow, step: record.step, params, history: record.history });
  await client.putProperty(key, cfg.jira.property, next);
  // From here on, failures are warnings: the branch is recorded.
  const meta: HistoryMetadata = { type: 'dfl', description: `dfl: ${record.step} (task branch)` };
  await projectFields({ client, cfg, key, current: issue.fields, params, deleted: [], meta, warnings });
  const status = trackedStatus({ cfg, model, issue, record: next, actual: issue.fields.status, via: 'arg', branch: currentBranch(ctx.paths.root), warnings });
  return { ...status, branch: { name: plan.name, action: plan.action === 'create' ? 'created' : 'current' }, resumed: true };
}

/** `TASK_DONE` when the record is at a final step of the flow. */
function assertNotDone(model: FlowModel, key: string, record: TaskRecord): void {
  if (!model.byId.get(record.step)?.final) return;
  throw new DflError(`${key} is already done (flow "${model.name}" is at its final step "${record.step}").`, {
    hint: `To work on it again, restart it with \`dfl goto ${model.initial} --task ${key}\`.`,
    code: 'TASK_DONE',
  });
}

/** A started task with a recorded branch: no writes; where its branch is. `TASK_DONE` at a final step. */
function resumeView(paths: ProjectPaths, cfg: TrackerConfig, model: FlowModel, issue: JiraIssue, record: TaskRecord, warnings: string[]): StartTaskResult {
  const key = issue.key;
  assertNotDone(model, key, record);
  const head = currentBranch(paths.root);
  // Passed the record checks (BRANCH_PARAM_RE), so it may appear in the warning and instructions.
  const recorded = record.params['branch'] || undefined;
  let branch: StartTaskResult['branch'];
  if (recorded === undefined || recorded === head) {
    branch = { name: recorded ?? head ?? '', action: 'current' };
  } else {
    const holder = worktreeHolding(paths.root, recorded);
    warnings.push(
      holder !== undefined
        ? `${key} lives on ${recorded}, which is checked out in the worktree ${holder}: continue there.`
        : `Switch to ${recorded} (git switch ${recorded}) to continue ${key}.`,
    );
    branch = { name: recorded, action: 'switch-needed' };
  }
  const status = trackedStatus({ cfg, model, issue, record, actual: issue.fields.status, via: 'arg', branch: head, warnings });
  return { ...status, branch, resumed: true };
}

type BranchPlan = { action: 'current' | 'create'; name: string; slug: string; from: string };

/** Which branch a new task uses (see {@link startTask}); throws the refusals. */
function planBranch(
  paths: ProjectPaths,
  cfg: TrackerConfig,
  settings: BranchSettings,
  input: { key: string; summary: string; head: string | undefined; mode: BranchMode; slug: string | undefined },
): BranchPlan {
  const { key, head, mode } = input;
  const slug = input.slug !== undefined ? slugify(input.slug) : slugify(input.summary);
  const name = renderBranchName(settings.template, key, slug);
  const from = settings.from;
  if (head !== undefined && keyFromBranch(head, cfg.jira.projectKeys) === key) {
    if (!BRANCH_PARAM_RE.test(head)) {
      throw new DflError(`The checked-out branch name has characters dfl does not record for a task (it allows letters, digits, ".", "_", "/", "+" and "-").`, {
        hint: `Rename the branch (git branch -m <new-name>), or switch to the main branch and run the command again to create a branch for ${key}.`,
        code: 'TASK_BRANCH_INVALID',
      });
    }
    // The branch is the user's choice: its slug (the part after the key) wins over the summary's.
    const ownSlug = input.slug !== undefined ? slug : (slugAfterKey(head, key) ?? slug);
    return { action: 'current', name: head, slug: ownSlug, from };
  }
  if (head === undefined) {
    const inGit = gitRoot(paths.root) !== undefined;
    throw new DflError(
      inGit ? `HEAD is detached, so dfl cannot tell which branch ${key} belongs on.` : `${paths.root} is not inside a git work tree, so dfl cannot bind ${key} to a branch.`,
      {
        hint: inGit
          ? `Switch to a branch first (the main branch to create one for ${key}, or a branch whose name contains ${key}), then run the command again.`
          : 'Run it in the git repository of the project.',
        code: 'TASK_BRANCH_DETACHED',
      },
    );
  }
  const isProtected = settings.protected.includes(head);
  if (mode === 'create' || (mode === 'auto' && isProtected)) {
    assertTaskBranchName(cfg, settings, key, name);
    return { action: 'create', name, slug, from };
  }

  const create = `pass branch "create" (CLI: \`dfl task start ${key} --branch create\`) to create ${name} from ${from}`;
  const headKey = keyFromBranch(head, cfg.jira.projectKeys);
  if (isProtected) {
    throw new DflError(`${head} is a protected branch: dfl does not record a task on it.`, {
      hint: `Leave out branch "current" to create ${name} from ${from}, or switch to a branch whose name contains ${key}.`,
      code: 'TASK_BRANCH_CHOICE',
    });
  }
  if (headKey !== undefined) {
    throw new DflError(`The checked-out branch ${head} belongs to ${headKey}, not to ${key}.`, {
      hint: `Switch to the main branch and run the command again (dfl then creates the branch of ${key}), or ${create}.`,
      code: 'TASK_BRANCH_CHOICE',
    });
  }
  throw new DflError(
    mode === 'current'
      ? `The checked-out branch ${head} does not contain ${key}: teammates find a task by the key in its branch name.`
      : `The checked-out branch ${head} does not contain ${key}, so dfl does not know whether to work on it or to create a new branch.`,
    {
      hint: `Either ${create}, or rename this branch to contain ${key} (git branch -m <new-name>) and run the command again.`,
      code: 'TASK_BRANCH_CHOICE',
    },
  );
}

/**
 * Throws DflError `TASK_BRANCH_INVALID` unless the rendered branch name `name` leads back to `key`
 * (`keyFromBranch`: e.g. the template `{key}{slug}` with the slug `2fa-…` would name ABC-22, not
 * ABC-2) and stays in the charset dfl records ({@link BRANCH_PARAM_RE}).
 */
function assertTaskBranchName(cfg: TrackerConfig, settings: BranchSettings, key: string, name: string): void {
  if (keyFromBranch(name, cfg.jira.projectKeys) !== key) {
    throw new DflError(`"${name}" (from the branch template "${settings.template}") does not name ${key}: dfl finds a task by the key in its branch name.`, {
      hint: `Put a separator such as "-" or "/" around {key} in the branch template in ${TRACKER_FILE_LABEL}, or pass another slug.`,
      code: 'TASK_BRANCH_INVALID',
    });
  }
  if (!BRANCH_PARAM_RE.test(name)) {
    throw new DflError(
      `"${name}" (from the branch template "${settings.template}") has characters dfl does not record for a task (it allows letters, digits, ".", "_", "/", "+" and "-").`,
      { hint: `Pass another slug, or fix the branch template in ${TRACKER_FILE_LABEL}.`, code: 'TASK_BRANCH_INVALID' },
    );
  }
}

/** Creates the task branch (fetching its base first, best-effort). */
async function createTaskBranch(root: string, plan: BranchPlan, settings: BranchSettings, warnings: string[]): Promise<void> {
  const { name, from } = plan;
  if (!isValidBranchName(name)) {
    throw new DflError(`"${name}" (from the branch template "${settings.template}") is not a valid git branch name.`, {
      hint: `Pass another slug, or fix the branch template in ${TRACKER_FILE_LABEL}.`,
      code: 'TASK_BRANCH_INVALID',
    });
  }
  if (localBranchExists(root, name)) {
    throw new DflError(`Branch ${name} already exists.`, {
      hint: `Switch to it (git switch ${name}) and run the command again to use it, or pass another slug.`,
      code: 'TASK_BRANCH_EXISTS',
    });
  }
  const fetched = settings.fetch ? await fetchBase(root, from) : undefined;
  if (!refExists(root, from)) {
    throw new DflError(`Cannot branch from ${from}: there is no such ref${fetched === false ? ' (and fetching it failed)' : ''}.`, {
      hint: `Check "branch.from" in ${TRACKER_FILE_LABEL} (default origin/<mainBranch>), or fetch it (git fetch), then run the command again.`,
      code: 'TASK_BRANCH_BASE_MISSING',
    });
  }
  if (fetched === false) warnings.push(`Could not fetch ${from}; ${name} was branched from the local ${from}, which may be behind.`);
  await createBranch(root, name, from);
}

/**
 * Fetches the branch of a remote-tracking `from` (`origin/main`) into it (`fetchBranch`: an explicit
 * refspec that never force-updates). Undefined when `from` is not on a configured remote or its
 * branch part is not a valid branch name (nothing to fetch), else whether the fetch worked.
 */
async function fetchBase(root: string, from: string): Promise<boolean | undefined> {
  const ref = from.startsWith('refs/remotes/') ? from.slice('refs/remotes/'.length) : from;
  const remote = listRemotes(root)
    .filter((name) => ref.startsWith(`${name}/`))
    .sort((a, b) => b.length - a.length)[0];
  if (remote === undefined) return undefined;
  const branch = ref.slice(remote.length + 1);
  if (!isValidBranchName(branch)) return undefined;
  return fetchBranch(root, remote, branch, FETCH_TIMEOUT_MS);
}

/** The slug part of a branch name after `key` (`feature/ABC-1-csv-export` → `csv-export`); undefined when there is none. */
function slugAfterKey(branch: string, key: string): string | undefined {
  const match = new RegExp(`(?<![A-Za-z0-9])${key}(?!\\d)`).exec(branch);
  if (!match) return undefined;
  const slug = slugify(branch.slice(match.index + key.length));
  return slug === '' ? undefined : slug;
}

