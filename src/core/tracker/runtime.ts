/**
 * True when `.df/tracker.json` exists and tracks `flowName`. A file whose `flows` does not name the
 * flow leaves it untracked even when the rest of the file is invalid or newer. Config errors
 * propagate (`TRACKER_CONFIG_*`) when the file is not a JSON object, or names the flow but is
 * invalid or newer.
 */
export function isTracked(paths: ProjectPaths, flowName: string): boolean {
  return trackerOf(paths, flowName) !== undefined;
}

/**
 * The position of `model`'s task and its ticket (`get_status`, `dfl status`). Undefined when the
 * flow is not tracked, or no ticket is bound and the flow does not require one: the caller then
 * uses the local state as for untracked flows.
 * - No ticket (requireTask): the initial step and `task.required`, with instructions to start one.
 * - Not started (no record, or one copied from another issue): the initial step, `started: false`.
 * - Started: the record's step. A step the flow no longer has gives the initial step with
 *   `repaired` and `task.stepUnknown` (moves are refused until a goto repairs it).
 * An explicit `task` may be a bare number (`123`, `#123`) when `jira.defaultProjectKey` is set: a
 * read cannot do harm with it (moves still need the full key).
 * Throws DflError `TASK_FLOW_MISMATCH` (the record belongs to another flow), `TASK_RECORD_INVALID`,
 * `TASK_SCHEMA_NEWER`, `TASK_BRANCH_MISMATCH`, `TASK_REF_*`, `TRACKER_AUTH_MISSING` and the HTTP errors.
 */
export async function taskStatus(
  paths: ProjectPaths,
  model: FlowModel,
  args: { task?: string | undefined } = {},
  opts: TaskReadOptions = {},
): Promise<TrackedStatus | undefined> {
  const tracker = trackerOf(paths, model.name);
  if (!tracker) return undefined;
  const { cfg, tracked } = tracker;
  const resolved = resolveTask(paths, cfg, { task: args.task, allowBare: true });
  if (!resolved) {
    if (!tracked.requireTask) return undefined;
    const suggested = suggestTask(paths, cfg, resolveBranchSettings(paths, cfg, model.def).protected);
    const task: RequiredTaskView = {
      provider: 'jira',
      key: null,
      started: false,
      required: true,
      ...(suggested !== undefined ? { suggested } : {}),
      warnings: [],
      instructions: taskInstructions({ kind: 'required', suggested, commandPrefix: opts.commandPrefix }),
    };
    return { state: runtimeFromStored(model, undefined), task };
  }

  const { client, warnings } = connect(cfg);
  const issue = await client.getIssue(resolved.key, { properties: [cfg.jira.property] });
  const read = readRecord(issue.properties[cfg.jira.property], issue);
  if (read.kind === 'invalid') throw read.error;
  if (read.kind === 'foreign') warnings.push(read.warning);
  const record = read.kind === 'ok' ? read.record : undefined;
  if (record && record.flow !== model.name) throw flowMismatchError(issue.key, record.flow, model.name);
  return trackedStatus({ cfg, model, issue, record, actual: issue.fields.status, via: resolved.via, branch: resolved.branch, warnings });
}

/**
 * Moves the task of `model` (complete_step / transition / goto_step, `dfl next/goto/reset`):
 * resolve the ticket → read its record → plan with the machine planners → write the record →
 * move the ticket to the status the new step maps to → write the mapped fields whose Jira value
 * differs from the record's params.
 * Undefined when the flow is not tracked, or no ticket is bound and the flow does not require one
 * (the caller then moves the local state).
 *
 * - An `event` move needs `from` (`TASK_FROM_REQUIRED`, unless `requireFrom: false`). When the
 *   record already shows that very move made by this process within {@link REPLAY_WINDOW_MS} (a
 *   retried call whose response was lost), the outcome is returned again with `replayed: true`
 *   after projecting the status and fields again (the lost call may have stopped before them).
 *   Without `from`, a record write that timed out (or lost its connection) is reported with a hint
 *   to check the status or repeat with `--from`: a plain repeat could advance the task twice.
 * - Only `goto` repairs an invalid record (a fresh record at the target step, keeping the current
 *   branch as `params.branch` when its name contains the key) or a record whose step the flow no
 *   longer has (`reset` too); an `event` move then fails with `TASK_RECORD_INVALID` / `TASK_STEP_UNKNOWN`.
 * - After the record is written nothing throws: projection and field failures are `task.warnings`.
 * Throws DflError `TASK_REQUIRED`, `TASK_NOT_STARTED`, `TASK_FLOW_MISMATCH`, `TASK_PARAM_INVALID`,
 * `TASK_RECORD_TOO_LARGE`, the planners' errors (`NOT_CURRENT`, `EVENT_NOT_ALLOWED`, `FLOW_DONE`,
 * `STEP_NOT_FOUND`), `TRACKER_AUTH_MISSING` and the HTTP errors (nothing written).
 */
export async function taskMove(paths: ProjectPaths, model: FlowModel, args: TaskMoveArgs, opts: TaskWriteOptions): Promise<TaskMoveResult | undefined> {
  const tracker = trackerOf(paths, model.name);
  if (!tracker) return undefined;
  const { cfg, tracked } = tracker;
  if (args.kind === 'goto') {
    if (args.step === undefined) throw new DflError('A goto needs the step to move to.', { code: 'INVALID_OPTIONS' });
    getStep(model, args.step);
  }
  if (args.kind === 'event' && args.from !== undefined) getStep(model, args.from);
  const resolved = resolveTask(paths, cfg, { task: args.task });
  if (!resolved) {
    if (!tracked.requireTask) return undefined;
    throw taskRequiredError(paths, cfg, model, opts.commandPrefix);
  }
  if (args.kind === 'event' && args.from === undefined && args.requireFrom !== false) {
    throw new DflError(`Flow "${model.name}" is tracked in Jira: an event must name the step it completes ("from").`, {
      hint: 'Pass from (CLI: `dfl next <EVENT> --from <step>`), or use complete_step: a retried call then cannot advance the task twice.',
      code: 'TASK_FROM_REQUIRED',
    });
  }
  return opts.withLock(() => moveTask(cfg, model, resolved, args, opts.commandPrefix));
}

/**
 * Starts (or resumes) work on a ticket (start_task, `dfl task start`): binds it to a git branch and
 * records the task at its first step.
 *
 * - The flow: `args.flow` → `flowSelect.byIssueType[<issue type>]` → `flowSelect.default` → the
 *   active flow; a started task keeps the flow of its record. It must be tracked
 *   (`TRACKER_FLOW_NOT_MAPPED`) and active (`TASK_FLOW_NOT_ACTIVE`).
 * - A started task is resumed without writes (`TASK_DONE` when it is at a final step); its branch is
 *   `current` when checked out, else `switch-needed` with a warning. A started task without a
 *   recorded branch (a record repaired by a goto) gets one as a new task would, recorded in
 *   `params.branch` under the lock (no step change, no status move).
 * - A new task (branch mode `auto`): the checked-out branch when its name contains the key; a new
 *   branch from `branch.from` (fetched first, best-effort) when on a protected branch or with mode
 *   `create`; else `TASK_BRANCH_CHOICE`. A new branch name must name the task (`keyFromBranch`)
 *   and stay in the charset of recorded branches. Then, under the lock: the record (event `START`,
 *   `params.branch` and `params.slug`, the lowercase key when the summary gives no slug), the status
 *   projection and the mapped fields.
 * Throws DflError `TRACKER_NOT_CONFIGURED`, `TRACKER_AUTH_MISSING`, `TASK_REF_*`, `TASK_RECORD_INVALID`,
 * `TASK_FLOW_MISMATCH` (an explicit flow other than the record's), `TASK_BRANCH_DETACHED`,
 * `TASK_BRANCH_INVALID`, `TASK_BRANCH_EXISTS`, `TASK_BRANCH_BASE_MISSING`, `TASK_BRANCH_FAILED`,
 * `STEP_NOT_FOUND`, `FINAL_STEP` and the HTTP errors.
 */
export async function startTask(paths: ProjectPaths, args: StartTaskArgs, opts: TaskWriteOptions): Promise<StartTaskResult> {
  const cfg = requireTrackerConfig(paths);
  const mode = args.branch ?? 'auto';
  if (!(BRANCH_MODES as readonly string[]).includes(mode)) {
    throw new DflError(`Unknown branch mode "${String(mode)}".`, { hint: `Use one of: ${BRANCH_MODES.join(', ')}.`, code: 'INVALID_OPTIONS' });
  }
  const ref = parseTaskRef(args.task, cfg, { allowBare: true });
  const property = cfg.jira.property;
  const { client: reader, credential, warnings } = connect(cfg);
  const issue = await reader.getIssue(ref, { properties: [property] });
  const key = issue.key;
  const read = readRecord(issue.properties[property], issue);
  if (read.kind === 'invalid') throw read.error;
  if (read.kind === 'foreign') warnings.push(read.warning);
  const existing = read.kind === 'ok' ? read.record : undefined;
  const model = selectFlow(paths, cfg, issue, existing, args.flow);
  const ctx: StartContext = { paths, cfg, ref, mode, slug: args.slug, credential, warnings, opts };
  if (existing) {
    if (args.step !== undefined && args.step !== existing.step) {
      warnings.push(`${key} is already started (at step "${existing.step}"), so step "${args.step}" was ignored: move it with \`dfl goto ${args.step} --task ${key}\`.`);
    }
    return resume(ctx, model, issue, existing);
  }

  const step = getStep(model, args.step ?? model.initial);
  if (step.final) {
    throw new DflError(`"${step.id}" is a final state of flow "${model.name}"; a task cannot start there.`, {
      hint: `Start at a step with work to do (default: the initial step "${model.initial}").`,
      code: 'FINAL_STEP',
    });
  }
  // A flow the machine cannot run fails here (INVALID_FLOW), not after the record is written.
  runtimeFromStored(model, undefined);

  // Git first (outside the lock: a fetch can take a while).
  assertConfiguredKey(cfg, ref, key);
  const settings = resolveBranchSettings(paths, cfg, model.def);
  const plan = planBranch(paths, cfg, settings, { key, summary: issue.fields.summary, head: currentBranch(paths.root), mode, slug: args.slug });
  if (plan.action === 'create') await createTaskBranch(paths.root, plan, settings, warnings);

  return opts.withLock(async () => {
    // A fresh deadline: the git work and the wait for the lock must not use up the writes' time.
    const client = clientFor(cfg, credential);
    const fresh = await client.getIssue(key, { properties: [property], fields: mappedFieldIds(cfg) });
    const again = readRecord(fresh.properties[property], fresh);
    if (again.kind === 'invalid') throw again.error;
    if (again.kind === 'ok') {
      // Started by another dfl process meanwhile: keep its record.
      warnings.push(`${key} was started by another dfl process meanwhile; dfl kept that record.`);
      if (again.record.flow !== model.name) throw flowMismatchError(key, again.record.flow, model.name);
      return again.record.params['branch'] ? resumeView(paths, cfg, model, fresh, again.record, warnings) : bindBranch(ctx, client, model, fresh, again.record, plan);
    }

    // The slug always exists for later steps, even when the summary gives none (another script).
    const params: Record<string, string> = { branch: plan.name, slug: plan.slug !== '' ? plan.slug : key.toLowerCase() };
    const record = buildRecord({
      issueId: fresh.id,
      key,
      flow: model.name,
      step: step.id,
      params,
      history: [recordHistoryEntry({ from: '', to: step.id, event: START_EVENT, at: new Date().toISOString() })],
    });
    await client.putProperty(key, property, record);
    // From here on, failures are warnings: the task is started.
    const meta = historyMetadata('', START_EVENT, step.id);
    const actual = await projectStatus({ client, cfg, flow: model.name, key, step: step.id, actual: actualStatus(fresh), start: true, meta, warnings });
    await projectFields({ client, cfg, key, current: fresh.fields, params, deleted: [], meta, warnings });
    const status = trackedStatus({ cfg, model, issue: fresh, record, actual, via: 'arg', branch: currentBranch(paths.root), warnings });
    return { ...status, branch: { name: plan.name, action: plan.action === 'create' ? 'created' : 'current' } };
  });
}

/** What read-only views show for a tracked flow instead of its local current step. */
export interface TrackedViewNote {
  /** `tracked in Jira (ABC-1): run \`dfl status\``, `tracked in Jira; no ticket on this branch`, or the invalid-config note. */
  note: string;
  /** The ticket of the current branch. */
  key?: string;
  /** `.df/tracker.json` names the flow but is invalid. */
  invalid?: true;
}

/**
 * For read-only views (flow list/view, step list, install summary) of a tracked flow: a note to
 * show instead of the local current step (`.df/state.json` is stale for tracked flows). Uses the
 * key in the current branch name; no network. Undefined for untracked flows; never throws.
 */
export function syncTrackedViewNote(paths: ProjectPaths, flow: FlowModel | string): TrackedViewNote | undefined {
  const name = typeof flow === 'string' ? flow : flow.name;
  try {
    if (!hasTrackerConfig(paths)) return undefined;
    let cfg: TrackerConfig | undefined;
    try {
      cfg = loadTrackerConfig(paths);
    } catch {
      // Invalid config: say so when the raw file names the flow.
      const flows = readTrackerConfigRaw(paths)?.['flows'];
      const named = typeof flows === 'object' && flows !== null && Object.hasOwn(flows, name);
      return named ? { note: `tracked in Jira, but ${TRACKER_FILE_LABEL} is invalid: run \`dfl tracker check\``, invalid: true } : undefined;
    }
    if (!cfg || !trackedFlow(cfg, name)) return undefined;
    const branch = currentBranch(paths.root);
    const key = branch !== undefined ? keyFromBranch(branch, cfg.jira.projectKeys) : undefined;
    return key !== undefined ? { note: `tracked in Jira (${key}): run \`dfl status\``, key } : { note: 'tracked in Jira; no ticket on this branch' };
  } catch {
    return undefined;
  }
}

