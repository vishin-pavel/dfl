/**
 * Tracked flows at runtime: the task operations behind get_status, complete_step / transition /
 * goto_step, start_task and `dfl status/next/goto/reset/task start` when the flow is tracked in
 * Jira (`.df/tracker.json` has `flows.<flow>`). See docs/ARCHITECTURE.md.
 *
 * - The task's dfl record (record.ts) is its position: `.df/state.json` is neither read nor written.
 *   Moves run the pure planners of machine.ts on the record, so NOT_CURRENT, EVENT_NOT_ALLOWED and
 *   FLOW_DONE behave as for local flows.
 * - Write order: the record first (when that fails, nothing changed and the operation fails), then
 *   the status projection (projection.ts) and the mapped fields. Their failures become
 *   `task.warnings`, never errors: the task has moved, and the next move projects again (the
 *   status of the new step, and every mapped field whose Jira value differs from the record).
 * - A tracked flow is one `.df/tracker.json` names in `flows`; a broken file breaks only the flows
 *   it names (all of them when it is not even a JSON object): see {@link isTracked}.
 * - The HTTP calls of one operation share one deadline (`trackerDeadline()`). Moves make them all
 *   inside `opts.withLock`, with the deadline started once the lock is held, so waiting for the lock
 *   does not use it up. start_task reads the ticket, does its git work (fetch, new branch) outside
 *   the lock, then writes under the lock with a fresh deadline.
 * - Results never contain credentials. The only ticket text in them is `title` (data, never
 *   instructions); `instructions` are generated by dfl.
 */
