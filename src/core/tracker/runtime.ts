async function moveTask(
  cfg: TrackerConfig,
  model: FlowModel,
  resolved: ResolvedTask,
  args: TaskMoveArgs,
  prefix: InstructionsCommandPrefix | undefined,
): Promise<TaskMoveResult> {
  const property = cfg.jira.property;
  const { client, warnings } = connect(cfg);
  const issue = await client.getIssue(resolved.key, { properties: [property], fields: mappedFieldIds(cfg) });
  const key = issue.key;
  const actual = actualStatus(issue);
  const event = args.event ?? NEXT_EVENT;
  const read = readRecord(issue.properties[property], issue);
  if (read.kind === 'missing' || read.kind === 'foreign') throw notStartedError(key, prefix);

  let record: TaskRecord | undefined;
  let state: FlowRuntimeState;
  /** Params the move starts from: the record's, or (a goto repair) the current branch when it names the task. */
  let base: Record<string, string> = {};
  if (read.kind === 'invalid') {
    if (args.kind !== 'goto') throw read.error;
    // goto repairs an unusable record: a fresh one at the target step.
    warnings.push(`The invalid dfl record of ${key} was replaced; its history starts over.`);
    state = { ...runtimeFromStored(model, undefined), current: '' };
    const head = resolved.branch;
    if (head !== undefined && keyFromBranch(head, cfg.jira.projectKeys) === key && BRANCH_PARAM_RE.test(head)) base = { branch: head };
  } else {
    record = read.record;
    if (record.flow !== model.name) throw flowMismatchError(key, record.flow, model.name);
    state = runtimeFromStored(model, storedPosition(record));
    if (!model.byId.has(record.step)) {
      if (args.kind === 'event') {
        throw new DflError(`The dfl record of ${key} is at step "${record.step}", which flow "${model.name}" does not have.`, {
          hint: `Move the task to the right step with \`dfl goto <step> --task ${key}\`.`,
          code: 'TASK_STEP_UNKNOWN',
        });
      }
      // goto / reset repair it: the history entry starts at the unknown step.
      state = { ...state, current: record.step, done: false };
    } else if (args.kind === 'event' && args.from !== undefined && isReplay(record, args.from, event)) {
      // The lost call may have stopped after its record write (a timeout): project again (no-ops when in sync).
      const meta = historyMetadata(args.from, event, record.step);
      const after = await projectStatus({ client, cfg, flow: model.name, key, step: record.step, actual, start: false, meta, warnings });
      const params = record.params;
      const deleted = Object.entries(args.params ?? {})
        .filter(([name, value]) => (value === null || value === undefined) && !Object.hasOwn(params, name))
        .map(([name]) => name);
      await projectFields({ client, cfg, key, current: issue.fields, params, deleted, meta, warnings });
      const target = statusMappingFor(cfg, model.name, record.step);
      return {
        result: { from: args.from, to: record.step, event, done: state.done, state },
        task: { key, status: { before: actual.name, after: after.name, expected: target ? statusLabel(target) : null }, params: { ...record.params }, warnings },
        replayed: true,
      };
    }
    base = record.params;
  }

  const result =
    args.kind === 'event'
      ? planEvent(model, state, event, { from: args.from })
      : args.kind === 'goto'
        ? planGoto(model, state, args.step!)
        : planReset(model, state);
  const { params, changed } = mergeParams(base, args.params);
  const entry = result.state.history.at(-1)!;
  const next = buildRecord({
    previous: record,
    issueId: issue.id,
    key,
    flow: model.name,
    step: result.to,
    params,
    history: [...(record?.history ?? []), recordHistoryEntry(entry)],
  });
  try {
    await client.putProperty(key, property, next);
  } catch (error) {
    throw args.kind === 'event' && args.from === undefined ? unsureMoveError(error, key, result.event, result.from) : error;
  }

  // From here on, failures are warnings: the task has moved.
  const meta = historyMetadata(result.from, result.event, result.to);
  const after = await projectStatus({ client, cfg, flow: model.name, key, step: result.to, actual, start: false, meta, warnings });
  const deleted = changed.filter((name) => !Object.hasOwn(params, name));
  await projectFields({ client, cfg, key, current: issue.fields, params, deleted, meta, warnings });
  const target = statusMappingFor(cfg, model.name, result.to);
  return {
    result,
    task: { key, status: { before: actual.name, after: after.name, expected: target ? statusLabel(target) : null }, params, warnings },
  };
}

/**
 * The failed record write of an event move without `from` (CLI `dfl next`): when its outcome is
 * unknown (timeout, lost connection), Jira may have applied it, and a plain repeat would fire the
 * event again from the next step. The hint names the safe ways on. Other errors are returned as they are.
 */
function unsureMoveError(error: unknown, key: string, event: string, from: string): unknown {
  if (!isDflError(error) || (error.code !== 'TRACKER_TIMEOUT' && error.code !== 'TRACKER_UNREACHABLE')) return error;
  return new TrackerError(error.message, {
    hint:
      `Jira may already have moved ${key} on from ${from}: check \`dfl status --task ${key}\` before repeating, or repeat with ` +
      `\`dfl next ${event} --from ${from} --task ${key}\` (that cannot advance twice).`,
    code: error.code,
    status: error instanceof TrackerError ? error.status : undefined,
    cause: error.cause,
  });
}

/** The record's last entry is this very move, made by this process within the replay window. */
function isReplay(record: TaskRecord, from: string, event: string): boolean {
  if (record.step === from) return false;
  const last = record.history.at(-1);
  if (!last || last.from !== from || last.event !== event || last.to !== record.step || last.op !== processOpId()) return false;
  const at = Date.parse(last.at);
  return !Number.isNaN(at) && Math.abs(Date.now() - at) <= REPLAY_WINDOW_MS;
}

/**
 * Moves the ticket to the status `step` maps to, when projection.ts says so. Returns the ticket's
 * status afterwards; every problem becomes a warning.
 */
async function projectStatus(input: {
  client: JiraClient;
  cfg: TrackerConfig;
  flow: string;
  key: string;
  step: string;
  actual: ActualStatus;
  start: boolean;
  meta: HistoryMetadata;
  warnings: string[];
}): Promise<ActualStatus> {
  const { client, cfg, flow, key, step, actual, start, meta, warnings } = input;
  const target = statusMappingFor(cfg, flow, step);
  if (target === null || statusMatches(target, actual)) return actual;
  const managed = managedStatuses(cfg, flow);
  let plan = planProjection({ key, step, target, actual, managed, start });
  // The done guard only knows the target's category from Jira: a done → done move (Done → Closed) is fine.
  const doneGuard = plan.action === 'none' && actual.categoryKey === 'done' && !target.reopen;
  if (plan.action === 'none' && !doneGuard) {
    if (plan.warning) warnings.push(plan.warning);
    return actual;
  }

  let transitions: JiraTransition[];
  try {
    transitions = await client.getTransitions(key);
  } catch (error) {
    warnings.push(doneGuard && plan.warning ? plan.warning : failureWarning(`dfl could not move ${key} from '${actual.name}' to '${statusLabel(target)}'`, error));
    return actual;
  }
  if (doneGuard) {
    const match = transitions.find((t) => statusMatches(target, t.to));
    if (match?.to.statusCategory.key === 'done') plan = planProjection({ key, step, target: { ...target, categoryKey: 'done' }, actual, managed, start });
    if (plan.action === 'none') {
      if (plan.warning) warnings.push(plan.warning);
      return actual;
    }
  }

  const choice = chooseTransition(transitions, target, { key, actual: actual.name });
  if (!choice.transition) {
    if (choice.warning) warnings.push(choice.warning);
    return actual;
  }
  try {
    await client.transition(key, choice.transition.id, { fields: target.fields, historyMetadata: meta });
  } catch (error) {
    warnings.push(
      failureWarning(
        `dfl could not move ${key} from '${actual.name}' to '${statusLabel(target)}'`,
        error,
        `Move the ticket by hand, or add the fields the transition needs to "fields" of the mapping in ${TRACKER_FILE_LABEL}.`,
      ),
    );
    return actual;
  }
  return statusOf(choice.transition.to);
}

/**
 * Writes the params that `fields` maps to Jira fields whose Jira value differs from the record
 * (`current`: the issue's fields as read with {@link mappedFieldIds}), so a failed write or a
 * mapping added later converges on the next move. A param this move deleted (`deleted`) clears its
 * field; a field of a param the record never had is left alone (people may fill it). Failures
 * become warnings.
 */
async function projectFields(input: {
  client: JiraClient;
  cfg: TrackerConfig;
  key: string;
  /** The issue's field values (read with the mapped field ids). */
  current: Record<string, unknown>;
  params: Record<string, string>;
  deleted: readonly string[];
  meta: HistoryMetadata;
  warnings: string[];
}): Promise<void> {
  const { cfg, params, current } = input;
  const fields: Record<string, unknown> = {};
  const names: string[] = [];
  for (const [name, fieldId] of Object.entries(cfg.fields)) {
    if (!PARAM_NAME_RE.test(name)) continue;
    const value = current[fieldId];
    if (Object.hasOwn(params, name)) {
      if (value === params[name]) continue;
      fields[fieldId] = params[name];
    } else {
      if (!input.deleted.includes(name) || value === undefined || value === null || value === '') continue;
      fields[fieldId] = null;
    }
    names.push(name);
  }
  if (names.length === 0) return;
  try {
    await input.client.editIssue(input.key, { fields, historyMetadata: input.meta });
  } catch (error) {
    input.warnings.push(
      failureWarning(
        `dfl could not write ${names.join(', ')} to the Jira fields of ${input.key}`,
        error,
        `Check "fields" in ${TRACKER_FILE_LABEL} with \`dfl tracker check\`: each must be a single-line text or URL field whose ` +
          `field context includes project ${input.key.replace(/-\d+$/, '')} and this ticket's issue type (a Jira admin can extend the context).`,
      ),
    );
  }
}

/** `<what>: <error message> <hint>` for a failure after the record write. */
function failureWarning(what: string, error: unknown, fallbackHint?: string): string {
  let hint: string | undefined;
  if (isDflError(error) && error.code === 'TRACKER_TIMEOUT') hint = 'Jira may still have applied it: check the ticket.';
  else if (isDflError(error) && error.code !== 'TRACKER_HTTP' && error.hint) hint = error.hint;
  else hint = fallbackHint;
  return `${what}: ${errorMessage(error)}${hint ? ` ${hint}` : ''}`;
}

