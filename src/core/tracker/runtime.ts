/**
 * A branch-name slug of `text`: NFKD with diacritics stripped, lowercase, every run of other
 * characters than a–z and 0–9 one `-`, no `-` at either end, at most `max` characters (cut at a
 * word boundary when there is one). Empty when nothing is left (e.g. a summary in another script).
 */
export function slugify(text: string, max: number = MAX_SLUG_LENGTH): string {
  const slug = text
    .normalize('NFKD')
    .replace(/\p{M}/gu, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
  if (slug.length <= max) return slug;
  const head = slug.slice(0, max + 1);
  const boundary = head.lastIndexOf('-');
  return (boundary > 0 ? head.slice(0, boundary) : slug.slice(0, max)).replace(/-+$/, '');
}

/**
 * `template` with `{key}` and `{slug}` filled in. An empty slug drops the placeholder together with
 * one adjacent `-`, `_` or `.` (`feature/{key}-{slug}` → `feature/ABC-1`).
 */
export function renderBranchName(template: string, key: string, slug: string): string {
  const text = slug === '' ? template.replace(/[-_.]\{slug\}|\{slug\}[-_.]?/g, '') : template;
  return text
    .replaceAll('{key}', key)
    .replaceAll('{slug}', slug)
    .replace(/\/{2,}/g, '/')
    .replace(/^\/+|\/+$/g, '');
}

