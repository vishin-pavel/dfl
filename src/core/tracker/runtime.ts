/**
 * The tracker config and the entry of `flow`; undefined when there is no tracker.json or it does not
 * name `flow` (then the rest of the file is not validated: see `loadTrackedFlow`).
 */
function trackerOf(paths: ProjectPaths, flow: string): { cfg: TrackerConfig; tracked: TrackedFlowConfig } | undefined {
  return loadTrackedFlow(paths, flow);
}

/** The Jira field ids `fields` maps params to (requested with the issue, so projectFields can compare). */
function mappedFieldIds(cfg: TrackerConfig): string[] {
  return [...new Set(Object.entries(cfg.fields).filter(([name]) => PARAM_NAME_RE.test(name)).map(([, id]) => id))];
}

/**
 * Throws DflError `TASK_REF_INVALID` when `key` (the issue's current key: Jira follows a moved
 * issue) is not of a configured project: a branch named after it could never be resolved.
 */
function assertConfiguredKey(cfg: TrackerConfig, ref: string, key: string): void {
  const project = key.slice(0, key.lastIndexOf('-'));
  if (cfg.jira.projectKeys.includes(project)) return;
  throw new DflError(
    `${ref} is now ${key}, and project ${project} is not configured for this repository (configured: ${cfg.jira.projectKeys.join(', ')}).`,
    {
      hint: `Add ${project} to "jira.projectKeys" in ${TRACKER_FILE_LABEL} (dfl finds a task by the key in its branch name), then run the command again.`,
      code: 'TASK_REF_INVALID',
    },
  );
}

/** A client for the configured site with a new deadline, plus the credential's warnings. `TRACKER_AUTH_MISSING` without a credential. */
function connect(cfg: TrackerConfig): { client: JiraClient; credential: TrackerCredential; warnings: string[] } {
  const credential = credentialFor(cfg.jira.origin);
  if (!credential) {
    throw new DflError(`No Jira credentials for ${cfg.jira.origin}.`, {
      hint:
        `Run \`dfl tracker login\` in your own terminal (dfl looks in ${credentialsFile()}, and in DFL_JIRA_URL, DFL_JIRA_EMAIL ` +
        'and DFL_JIRA_TOKEN for CI). Never paste a token into a chat.',
      code: 'TRACKER_AUTH_MISSING',
    });
  }
  return { client: clientFor(cfg, credential), credential, warnings: [...credential.warnings] };
}

/** A client whose requests share a deadline that starts now. */
function clientFor(cfg: TrackerConfig, credential: TrackerCredential): JiraClient {
  return createJiraClient({ baseUrl: cfg.jira.baseUrl, credential, signal: trackerDeadline() });
}

function actualStatus(issue: JiraIssue): ActualStatus {
  return statusOf(issue.fields.status);
}

function statusOf(status: JiraStatus): ActualStatus {
  return {
    id: status.id,
    name: status.name,
    ...(status.untranslatedName !== undefined ? { untranslatedName: status.untranslatedName } : {}),
    categoryKey: status.statusCategory.key,
  };
}

/** The tracked status of a bound ticket (not started when `record` is undefined). */
function trackedStatus(input: {
  cfg: TrackerConfig;
  model: FlowModel;
  issue: JiraIssue;
  record: TaskRecord | undefined;
  /** The ticket's status now (after a projection, when there was one). */
  actual: { id: string; name: string };
  via: 'arg' | 'branch';
  /** The checked-out branch. */
  branch: string | undefined;
  warnings: string[];
}): { state: FlowRuntimeState; task: BoundTaskView } {
  const { cfg, model, issue, record, actual, via, warnings } = input;
  const key = issue.key;
  const common = { provider: 'jira' as const, key, url: browseUrl(cfg, key), title: issue.fields.summary };
  if (!record) {
    return {
      state: runtimeFromStored(model, undefined),
      task: {
        ...common,
        started: false,
        status: { actual: actual.name, expected: null, inSync: true },
        params: {},
        branch: null,
        via,
        warnings,
        instructions: taskInstructions({ kind: 'not-started', key }),
      },
    };
  }

  const params = { ...record.params };
  const branch = params['branch'] || null;
  const state = runtimeFromStored(model, storedPosition(record));
  if (!model.byId.has(record.step)) {
    state.repaired =
      `The dfl record of ${key} is at step "${record.step}", which flow "${model.name}" no longer has; ` +
      `showing the initial step "${state.current}" until a goto repairs it.`;
    warnings.push(
      `The dfl record of ${key} is at step "${record.step}", which flow "${model.name}" no longer has: moves are refused ` +
        `until you move it to the right step with \`dfl goto <step> --task ${key}\`.`,
    );
    return {
      state,
      task: {
        ...common,
        started: true,
        status: { actual: actual.name, expected: null, inSync: true },
        params,
        branch,
        via,
        warnings,
        instructions: taskInstructions({ kind: 'step-unknown', key, step: record.step, flow: model.name }),
        stepUnknown: record.step,
      },
    };
  }

  const target = statusMappingFor(cfg, model.name, state.current);
  return {
    state,
    task: {
      ...common,
      started: true,
      step: state.current,
      status: { actual: actual.name, expected: target ? statusLabel(target) : null, inSync: target === null || statusMatches(target, actual) },
      params,
      branch,
      via,
      warnings,
      instructions: taskInstructions({
        kind: 'started',
        key,
        step: state.current,
        final: state.done,
        events: availableEvents(model, state.current).map((t) => t.event),
        branch,
        currentBranch: input.branch,
        fieldParams: Object.keys(cfg.fields),
      }),
    },
  };
}

function taskRequiredError(paths: ProjectPaths, cfg: TrackerConfig, model: FlowModel, prefix: InstructionsCommandPrefix | undefined): DflError {
  const suggested = suggestTask(paths, cfg, resolveBranchSettings(paths, cfg, model.def).protected);
  const example = `${cfg.jira.defaultProjectKey ?? cfg.jira.projectKeys[0]}-123`;
  return new DflError(`Flow "${model.name}" is tracked in Jira, but no ticket is bound to the current branch.`, {
    hint:
      `Start one with ${prefix ?? '/'}${INIT_TASK_SKILL} <ticket> (CLI: \`dfl task start <ticket>\`), or pass the task (its key, e.g. ${example}).` +
      (suggested !== undefined ? ` The previous branch was for ${suggested}: pass it if that is the task you just finished.` : ''),
    code: 'TASK_REQUIRED',
  });
}

function notStartedError(key: string, prefix: InstructionsCommandPrefix | undefined): DflError {
  return new DflError(`${key} has no dfl task yet.`, {
    hint: `Start it with ${prefix ?? '/'}${INIT_TASK_SKILL} ${key} (CLI: \`dfl task start ${key}\`).`,
    code: 'TASK_NOT_STARTED',
  });
}

function flowMismatchError(key: string, recordFlow: string, flow: string): DflError {
  return new DflError(`${key} is a task of flow "${recordFlow}", not of flow "${flow}".`, {
    hint: `Run \`dfl flow use ${recordFlow}\` to continue it (restart your agent if it does not pick up the new skills).`,
    code: 'TASK_FLOW_MISMATCH',
  });
}
